import { Pet } from '../core/models';
import { Lang } from '../core/i18n/strings';
import { pick } from '../shared/utils/random';

/* Фразы похвалы/ошибки с именем питомца. {м|ж} — форма по полу питомца. Новый язык — ещё один блок. */
type Set = { ok: string[]; bad: string[] };
const PHRASES: Record<Lang, { cat: Set; dog: Set; none: Set }> = {
  ru: {
    cat: {
      ok: ['{n} от радости {покатался|покаталась} по полу! 🐾', '{n} гордо {поднял|подняла} хвост!', '{n} мурчит: «Правильно!»', 'Умница! {n} {доволен|довольна} 😺'],
      bad: ['Ой! {n} {лёг|легла} на ответ… Попробуй ещё 🙀', '{n} смотрит с подозрением 🤨', 'Почти! {n} ждёт другой ответ.'],
    },
    dog: {
      ok: ['Гав! {n} радостно виляет хвостом! 🐶', '{n} {принёс|принесла} тебе мячик — правильно!', '{n} прыгает от радости!', 'Умница! {n} {доволен|довольна}'],
      bad: ['{n} наклонил{|а} голову: «Точно?» 🐶', 'Р-р… {n} не {согласен|согласна}. Подумай ещё.', 'Почти! {n} ждёт другой ответ.'],
    },
    none: { ok: ['Верно!', 'Отлично!', 'Так держать!'], bad: ['Почти! Подумай ещё.', 'Не совсем. Попробуй ещё раз.'] },
  },
  by: {
    cat: {
      ok: ['{n} ад радасці {пакачаўся|пакачалася} па падлозе! 🐾', '{n} горда {падняў|падняла} хвост!', '{n} муркоча: «Правільна!»', 'Разумніца! {n} {задаволены|задаволеная} 😺'],
      bad: ['Ой! {n} {лёг|легла} на адказ… Паспрабуй яшчэ 🙀', '{n} глядзіць з падазрэннем 🤨', 'Амаль! {n} чакае іншы адказ.'],
    },
    dog: {
      ok: ['Гаў! {n} радасна віляе хвастом! 🐶', '{n} {прынёс|прынесла} табе мячык — правільна!', '{n} скача ад радасці!', 'Разумніца! {n} {задаволены|задаволеная}'],
      bad: ['{n} нахілі{ў|ла} галаву: «Дакладна?» 🐶', 'Р-р… {n} не {згодны|згодная}. Падумай яшчэ.', 'Амаль! {n} чакае іншы адказ.'],
    },
    none: { ok: ['Правільна!', 'Выдатна!', 'Так трымаць!'], bad: ['Амаль! Падумай яшчэ.', 'Не зусім. Паспрабуй яшчэ раз.'] },
  },
};

function fill(t: string, p: Pet) {
  return t.replace(/\{n\}/g, p.name).replace(/\{([^|{}]*)\|([^|{}]*)\}/g, (_, m, f) => (p.sex === 'f' ? f : m));
}

/** Случайная фраза: ok — похвала, иначе — «подумай ещё». pet = null → нейтрально. */
export function petPhrase(pet: Pet | null, ok: boolean, lang: Lang = 'ru'): string {
  const L = PHRASES[lang] ?? PHRASES.ru;
  if (!pet) return pick(ok ? L.none.ok : L.none.bad);
  const set = pet.kind === 'dog' ? L.dog : L.cat;
  return fill(pick(ok ? set.ok : set.bad), pet);
}
