const {chromium}=await import(process.env.PW);
import fs from 'fs';
const b=await chromium.launch();const p=await b.newPage();
const errs=[];p.on('pageerror',e=>errs.push(e.message));
await p.goto('file://'+process.cwd()+'/zadachi.html');
const r=await p.evaluate(()=>{const T=window.__TEST__;const bad=[];const samples={};
 for(const it of T.ITEMS){for(let n=0;n<300;n++){it.inst=T.makeInst(it);const sp=T.mainSpecs(it);
  const txt=it.inst.text;if(/undefined|NaN|\$\{/.test(txt))bad.push(['txt',it.id,txt]);
  sp.forEach((s,j)=>{if(s.opts&&!s.opts.includes(s.ans))bad.push(['ans',it.id,j,s.ans,s.opts]);
   if(s.opts&&new Set(s.opts).size!==s.opts.length)bad.push(['dup',it.id,s.opts]);
   if(s.opts&&s.opts.length<2)bad.push(['few',it.id,s.opts]);
   if(s.cards&&!s.cards.some(c=>c.v===s.ans))bad.push(['card',it.id]);
   if(s.num&&!/^\d+$/.test(s.ans))bad.push(['num',it.id,s.ans]);});
  const sol=T.solved(it);if(/undefined|NaN/.test(sol))bad.push(['sol',it.id,sol.slice(0,200)]);
  if(n<2)(samples[it.id]=samples[it.id]||[]).push(txt+' → '+it.ans(it.inst.x));
 }}return {bad:bad.slice(0,30),n:bad.length,samples};});
console.log(JSON.stringify(r.bad,null,0).slice(0,3000));console.log('bad',r.n,'errs',errs);
for(const [k,v] of Object.entries(r.samples))console.log(k,'|',v.join(' || '));
await b.close();
